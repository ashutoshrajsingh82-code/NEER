def generate_demo_dataset(
    environment: str = "demo", n_time: int = DEFAULT_N_TIME, seed: int | None = None
) -> Tuple[Dict[str, np.ndarray], dict]:
    """Generate the full synthetic demo dataset and its metadata dict."""
    config = load_config(environment)
    seed = config.demo.seed if seed is None else seed
    rng = np.random.default_rng(seed)

    grid = create_ocean_grid(config.domain)
    depths = list(config.depths)

    timestamps = [DEFAULT_START_DATE + timedelta(days=30.44 * i) for i in range(n_time)]
    day_of_year = np.array([ts.timetuple().tm_yday for ts in timestamps], dtype=float)

    ocean_mask = build_land_ocean_mask(grid.lat_grid, grid.lon_grid)

    eddies = _make_eddies(rng, n_eddies=6, grid=grid)
    sla = generate_sla(grid, eddies, n_time)
    sst = generate_sst(grid, sla, rng, day_of_year)
    sss = generate_sss(grid, sla, rng, day_of_year)
    u_wind, v_wind = generate_winds(grid, rng, day_of_year)
    u_current, v_current = generate_currents(grid, sla, day_of_year, rng)
    subsurface_temp = generate_subsurface_temperature(grid, depths, sst, sla, day_of_year, rng)

    data = {
        "sst": sst,
        "sss": sss,
        "sla": sla,
        "u_current": u_current,
        "v_current": v_current,
        "u_wind": u_wind,
        "v_wind": v_wind,
        "subsurface_temp": subsurface_temp,
    }
    apply_missing_values(data, ocean_mask, rng)

    data["land_mask"] = ocean_mask  # keep the name "land_mask", values True=ocean (documented)
    data["latitude"] = grid.latitudes.astype(np.float32)
    data["longitude"] = grid.longitudes.astype(np.float32)
    data["depth"] = np.asarray(depths, dtype=np.float32)
    data["time"] = np.array([ts.strftime("%Y-%m-%d") for ts in timestamps])

    metadata = {
        "data_mode": DATA_MODE,
        "disclaimer": DISCLAIMER,
        "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "generator": "scripts/create_demo_data.py",
        "project": "NEER",
        "problem_id": "SIH26066",
        "organization": "MoES / INCOIS",
        "seed": int(seed),
        "environment": environment,
        "domain": {
            "lat_min": config.domain.lat_min,
            "lat_max": config.domain.lat_max,
            "lon_min": config.domain.lon_min,
            "lon_max": config.domain.lon_max,
            "resolution_deg": config.domain.resolution,
        },
        "grid_shape": {"n_lat": grid.shape[0], "n_lon": grid.shape[1]},
        "depths_m": depths,
        "n_time_steps": n_time,
        "time_range": [data["time"][0], data["time"][-1]],
        "variables": {
            "sst": {"dims": ["time", "lat", "lon"], "units": "degC", "description": "Sea surface temperature (synthetic)"},
            "sss": {"dims": ["time", "lat", "lon"], "units": "psu", "description": "Sea surface salinity (synthetic)"},
            "sla": {"dims": ["time", "lat", "lon"], "units": "m", "description": "Sea level anomaly (synthetic)"},
            "u_current": {"dims": ["time", "lat", "lon"], "units": "m/s", "description": "Zonal surface current (synthetic)"},
            "v_current": {"dims": ["time", "lat", "lon"], "units": "m/s", "description": "Meridional surface current (synthetic)"},
            "u_wind": {"dims": ["time", "lat", "lon"], "units": "m/s", "description": "Zonal wind (synthetic)"},
            "v_wind": {"dims": ["time", "lat", "lon"], "units": "m/s", "description": "Meridional wind (synthetic)"},
            "subsurface_temp": {"dims": ["time", "depth", "lat", "lon"], "units": "degC", "description": "Subsurface temperature at all 15 target depths (synthetic)"},
            "land_mask": {"dims": ["lat", "lon"], "units": "bool", "description": "True = ocean, False = land (schematic, hand-built approximation, not a real coastline product)"},
        },
        "missing_values": "NaN over land and over synthetic gap patches (cloud-like for surface fields, sparser ARGO-like coverage for subsurface_temp)",
    }
    return data, metadata


def save_dataset(data: Dict[str, np.ndarray], metadata: dict, output_dir: Path) -> Tuple[Path, Path]:
    output_dir.mkdir(parents=True, exist_ok=True)
    npz_path = output_dir / "neer_demo_ocean_dataset.npz"
    meta_path = output_dir / "neer_demo_metadata.json"

    np.savez_compressed(npz_path, **data)
    with open(meta_path, "w", encoding="utf-8") as f:
        json.dump(metadata, f, indent=2)

    return npz_path, meta_path


