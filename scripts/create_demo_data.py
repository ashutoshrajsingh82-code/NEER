def _smooth_random_field(
    rng: np.random.Generator, shape: Tuple[int, int], smoothing: int = 9
) -> np.ndarray:
    """A spatially-correlated pseudo-random field in roughly [-1, 1].

    Built with a simple repeated box-blur (no extra dependency needed)
    over white noise, then rescaled. Used for weather-like/cloud-like
    noise textures rather than pixel-independent noise.
    """
    field = rng.standard_normal(shape)
    kernel = np.ones(smoothing) / smoothing
    for _ in range(3):
        field = np.apply_along_axis(lambda m: np.convolve(m, kernel, mode="same"), 0, field)
        field = np.apply_along_axis(lambda m: np.convolve(m, kernel, mode="same"), 1, field)
    peak = np.max(np.abs(field))
    return field / peak if peak > 0 else field


def _season_frac(day_of_year: np.ndarray | float, period_days: float = 365.25) -> np.ndarray:
    """Fractional position in the annual cycle, in [0, 1)."""
    return (np.asarray(day_of_year, dtype=float) % period_days) / period_days


@dataclass(frozen=True)
class Eddy:
    """A single Gaussian mesoscale-eddy-like anomaly."""

    lat0: float
    lon0: float
    radius_deg: float
    amplitude_m: float  # signed: + anticyclonic (warm-core), - cyclonic (cold-core)
    drift_lon_per_step: float  # westward propagation per time step (deg)


def _make_eddies(rng: np.random.Generator, n_eddies: int, grid: OceanGrid) -> list[Eddy]:
    lat_min, lat_max, lon_min, lon_max = grid.bounds
    # Guarantee a mix of cyclonic (cold-core, -) and anticyclonic (warm-core,
    # +) eddies rather than leaving the sign split to chance, which would
    # occasionally (im)plausibly produce an all-one-sign eddy field.
    signs = np.array([1.0, -1.0] * ((n_eddies + 1) // 2))[:n_eddies]
    rng.shuffle(signs)

    eddies = []
    for sign in signs:
        lat0 = rng.uniform(lat_min + 2, lat_max - 4)
        lon0 = rng.uniform(lon_min + 8, lon_max - 8)
        radius = rng.uniform(1.2, 3.0)  # degrees (~130-330 km)
        amp = rng.uniform(0.08, 0.22) * sign
        drift = rng.uniform(0.15, 0.5)  # mesoscale eddies drift westward
        eddies.append(Eddy(lat0, lon0, radius, amp, drift))
    return eddies


def _eddy_field(eddies: list, lat_grid: np.ndarray, lon_grid: np.ndarray, t: int) -> np.ndarray:
    field = np.zeros(lat_grid.shape, dtype=np.float64)
    for e in eddies:
        lon_t = e.lon0 - e.drift_lon_per_step * t
        d2 = (lat_grid - e.lat0) ** 2 + (lon_grid - lon_t) ** 2
        field += e.amplitude_m * np.exp(-d2 / (2 * e.radius_deg**2))
    return field


