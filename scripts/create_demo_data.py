def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--environment", default="demo", choices=["base", "demo", "development", "production"])
    parser.add_argument("--n-time", type=int, default=DEFAULT_N_TIME, help="Number of time steps to generate")
    parser.add_argument("--seed", type=int, default=None, help="Override the seed from configs/*.yaml")
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=PROJECT_ROOT / "data" / "demo",
        help="Directory to write the demo dataset into (default: data/demo)",
    )
    args = parser.parse_args()

    logger.info("Generating synthetic demo dataset (data_mode=%s)...", DATA_MODE)
    data, metadata = generate_demo_dataset(
        environment=args.environment, n_time=args.n_time, seed=args.seed
    )

    logger.info("Saving dataset to %s ...", args.output_dir)
    npz_path, meta_path = save_dataset(data, metadata, args.output_dir)
    logger.info("Wrote %s and %s", npz_path, meta_path)

    logger.info("Verifying generated dataset...")
    verify_dataset(npz_path, meta_path)
    logger.info("Done. This dataset is SYNTHETIC (data_mode=DEMO_SYNTHETIC) — not real observational data.")


if __name__ == "__main__":
    main()
