def verify_dataset(npz_path: Path, meta_path: Path) -> None:
    """Reload the saved files and sanity-check shapes, dtypes, data_mode,
    and the presence of missing values / masking. Raises AssertionError
    on any failed check.
    """
    with open(meta_path, "r", encoding="utf-8") as f:
        metadata = json.load(f)

    assert metadata["data_mode"] == DATA_MODE, "data_mode must be DEMO_SYNTHETIC"
    assert "disclaimer" in metadata and metadata["disclaimer"], "disclaimer missing"
    assert "satellite" not in metadata["disclaimer"].lower() or "not" in metadata["disclaimer"].lower()

    npz = np.load(npz_path, allow_pickle=False)
    n_lat = metadata["grid_shape"]["n_lat"]
    n_lon = metadata["grid_shape"]["n_lon"]
    n_time = metadata["n_time_steps"]
    n_depth = len(metadata["depths_m"])

    expected_shapes = {
        "sst": (n_time, n_lat, n_lon),
        "sss": (n_time, n_lat, n_lon),
        "sla": (n_time, n_lat, n_lon),
        "u_current": (n_time, n_lat, n_lon),
        "v_current": (n_time, n_lat, n_lon),
        "u_wind": (n_time, n_lat, n_lon),
        "v_wind": (n_time, n_lat, n_lon),
        "subsurface_temp": (n_time, n_depth, n_lat, n_lon),
        "land_mask": (n_lat, n_lon),
        "latitude": (n_lat,),
        "longitude": (n_lon,),
        "depth": (n_depth,),
        "time": (n_time,),
    }

    for name, shape in expected_shapes.items():
        assert name in npz, f"missing array: {name}"
        assert npz[name].shape == shape, f"{name} shape {npz[name].shape} != expected {shape}"

    land_mask = npz["land_mask"]
    assert land_mask.dtype == bool, "land_mask must be boolean"
    assert 0 < land_mask.mean() < 1, "land_mask should contain both land and ocean points"

    # Land points must be NaN in every surface field, at every time step.
    land_points = ~land_mask
    assert land_points.sum() > 0, "expected at least one land point in the synthetic mask"
    assert np.isnan(npz["sst"][0][land_points]).all(), "land points must be NaN in sst"

    # Ocean points should have *some* missing values (gaps) but not be
    # entirely missing.
    ocean_sst_t0 = npz["sst"][0][land_mask]
    frac_missing = np.isnan(ocean_sst_t0).mean()
    assert 0.0 < frac_missing < 0.9, f"unexpected ocean-point missing fraction for sst: {frac_missing:.2f}"

    # Subsurface temperature should decrease with depth on average
    # (thermocline structure) at ocean points, ignoring NaNs.
    subsurface = npz["subsurface_temp"]
    # Allow a small tolerance for noise averaging in the near-isothermal
    # abyssal layer (deep levels hover around the same reference
    # temperature with independent per-depth noise).
    mean_by_depth = np.nanmean(subsurface[:, :, land_mask], axis=(0, 2))
    assert np.all(np.diff(mean_by_depth) <= 0.05), "mean temperature should not increase with depth"

    # depths must match config exactly and be ascending
    depths = npz["depth"]
    assert list(depths) == sorted(depths), "depths must be ascending"
    assert len(depths) == 15, f"expected 15 depth levels, got {len(depths)}"

    logger.info(
        "Verification OK: shapes match, data_mode=%s, land_mask ocean_frac=%.3f, "
        "sst ocean missing_frac(t=0)=%.3f, thermocline mean profile is non-increasing with depth.",
        metadata["data_mode"],
        land_mask.mean(),
        frac_missing,
    )


