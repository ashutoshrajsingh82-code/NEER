def generate_sla(grid: OceanGrid, eddies: list, n_time: int) -> np.ndarray:
    """Sea Level Anomaly: dominated by drifting Gaussian eddies, near-zero mean."""
    out = np.empty((n_time, *grid.shape), dtype=np.float32)
    for t in range(n_time):
        out[t] = _eddy_field(eddies, grid.lat_grid, grid.lon_grid, t)
    return out


def generate_sst(
    grid: OceanGrid, sla: np.ndarray, rng: np.random.Generator, day_of_year: np.ndarray
) -> np.ndarray:
    """Sea Surface Temperature: tropical warm base, monsoon seasonal cycle,
    upwelling-driven cooling off the Arabian Sea western boundary in
    summer monsoon, eddy-correlated anomaly (+eddy=warm core), noise.
    """
    n_time = sla.shape[0]
    lat, lon = grid.lat_grid, grid.lon_grid
    out = np.empty((n_time, *grid.shape), dtype=np.float32)

    base = 29.5 - 0.12 * (lat - 5.0)  # warm equatorward, cooler poleward
    for t in range(n_time):
        frac = _season_frac(day_of_year[t])
        seasonal = 1.2 * np.sin(2 * np.pi * (frac - 0.15))  # peaks ~ pre-monsoon (May)

        # Somali/Omani coastal upwelling: cooling near western boundary
        # (low lon), strongest during the SW monsoon (Jun-Sep, frac ~0.45-0.75).
        monsoon_strength = max(0.0, np.sin(2 * np.pi * (frac - 0.45)))
        upwelling = -2.5 * monsoon_strength * np.exp(-((lon - 52.0) ** 2) / (2 * 6.0**2))

        eddy_anom = 2.0 * sla[t]  # warm-core (+SLA) / cold-core (-SLA)
        noise = 0.25 * _smooth_random_field(rng, grid.shape)

        out[t] = base + seasonal + upwelling + eddy_anom + noise
    return out


def generate_sss(
    grid: OceanGrid, sla: np.ndarray, rng: np.random.Generator, day_of_year: np.ndarray
) -> np.ndarray:
    """Sea Surface Salinity: saltier Arabian Sea (west, evaporation-driven),
    fresher Bay of Bengal (east, river-runoff/monsoon-rain driven), with a
    monsoon-season freshening pulse on the Bay of Bengal side.
    """
    n_time = sla.shape[0]
    lon = grid.lon_grid
    out = np.empty((n_time, *grid.shape), dtype=np.float32)

    lon_min, lon_max = grid.bounds[2], grid.bounds[3]
    lon_frac = (lon - lon_min) / (lon_max - lon_min)  # 0 west .. 1 east
    base = 36.5 - 3.5 * lon_frac  # ~36.5 psu Arabian Sea -> ~33 psu Bay of Bengal

    for t in range(n_time):
        frac = _season_frac(day_of_year[t])
        monsoon_strength = max(0.0, np.sin(2 * np.pi * (frac - 0.45)))
        bay_freshening = -1.2 * monsoon_strength * lon_frac  # stronger toward the east
        eddy_anom = -0.3 * sla[t]
        noise = 0.08 * _smooth_random_field(rng, grid.shape)
        out[t] = base + bay_freshening + eddy_anom + noise
    return out


def generate_winds(
    grid: OceanGrid, rng: np.random.Generator, day_of_year: np.ndarray
) -> Tuple[np.ndarray, np.ndarray]:
    """U/V wind: idealised Indian-monsoon reversal — strong southwesterly
    flow Jun-Sep, weaker northeasterly flow Dec-Feb, plus synoptic noise.
    """
    n_time = len(day_of_year)
    u = np.empty((n_time, *grid.shape), dtype=np.float32)
    v = np.empty((n_time, *grid.shape), dtype=np.float32)

    for t in range(n_time):
        frac = _season_frac(day_of_year[t])
        # Single annual harmonic: positive (SW monsoon) around Jul (frac~0.55),
        # negative (NE monsoon, weaker) around Jan (frac~0.04).
        monsoon = np.sin(2 * np.pi * (frac - 0.3))
        u_bg = 6.0 * monsoon
        v_bg = 4.0 * monsoon
        synoptic_u = 1.5 * _smooth_random_field(rng, grid.shape, smoothing=13)
        synoptic_v = 1.5 * _smooth_random_field(rng, grid.shape, smoothing=13)
        u[t] = u_bg + synoptic_u
        v[t] = v_bg + synoptic_v
    return u, v


def generate_currents(
    grid: OceanGrid, sla: np.ndarray, day_of_year: np.ndarray, rng: np.random.Generator
) -> Tuple[np.ndarray, np.ndarray]:
    """U/V surface currents: an approximate geostrophic response to the SLA
    field, plus a seasonally-reversing background jet (Somali-Current-like
    western-boundary intensification during the SW monsoon), plus noise.
    """
    n_time = sla.shape[0]
    lat, lon = grid.lat_grid, grid.lon_grid
    lat_rad = np.deg2rad(lat)
    dlat_rad = np.deg2rad(grid.resolution)
    dlon_rad = np.deg2rad(grid.resolution)
    f = 2 * EARTH_OMEGA * np.sin(lat_rad)
    f = np.where(np.abs(f) < 1e-6, 1e-6, f)  # guard divide-by-zero (not hit in this domain)

    u = np.empty((n_time, *grid.shape), dtype=np.float32)
    v = np.empty((n_time, *grid.shape), dtype=np.float32)

    lon_min = grid.bounds[2]
    western_boundary_weight = np.exp(-(lon - lon_min) / 8.0)  # decays eastward

    for t in range(n_time):
        d_sla_dlat = np.gradient(sla[t].astype(np.float64), axis=0) / dlat_rad
        d_sla_dlon = np.gradient(sla[t].astype(np.float64), axis=1) / dlon_rad
        d_sla_dy = d_sla_dlat / EARTH_RADIUS_M
        d_sla_dx = d_sla_dlon / (EARTH_RADIUS_M * np.cos(lat_rad))

        u_geo = -(GRAVITY / f) * d_sla_dy
        v_geo = (GRAVITY / f) * d_sla_dx

        frac = _season_frac(day_of_year[t])
        monsoon = np.sin(2 * np.pi * (frac - 0.3))
        u_bg = 0.5 * monsoon * western_boundary_weight
        v_bg = 0.3 * monsoon * western_boundary_weight

        noise = 0.03 * _smooth_random_field(rng, grid.shape)
        u[t] = u_geo + u_bg + noise
        v[t] = v_geo + v_bg + noise

    return u, v


def generate_subsurface_temperature(
    grid: OceanGrid,
    depths: list,
    sst: np.ndarray,
    sla: np.ndarray,
    day_of_year: np.ndarray,
    rng: np.random.Generator,
) -> np.ndarray:
    """Subsurface temperature at every configured depth: a tanh thermocline
    profile between the (already-generated) SST and an abyssal temperature,
    with a thermocline depth that shoals in winter monsoon (convective
    mixing) and deepens in summer, and is further perturbed by eddies
    (anticyclonic/warm-core eddies deepen the thermocline, cyclonic ones
    shoal it) — a simple, deliberately illustrative analogue of real
    eddy-thermocline interaction.
    """
    n_time = sst.shape[0]
    depths_arr = np.asarray(depths, dtype=np.float64)
    deep_temp = 4.0  # degC abyssal reference

    out = np.empty((n_time, len(depths), *grid.shape), dtype=np.float32)

    for t in range(n_time):
        frac = _season_frac(day_of_year[t])
        # Winter (NE monsoon, frac~0.0-0.15) convective mixing -> shallow
        # mixed layer/thermocline; summer stratification -> deeper.
        seasonal_mld = 30.0 * np.sin(2 * np.pi * (frac - 0.55))
        thermocline_depth = 110.0 + seasonal_mld - 60.0 * sla[t]
        thermocline_depth = np.clip(thermocline_depth, 40.0, 220.0)
        thermocline_width = 35.0 + 5.0 * _smooth_random_field(rng, grid.shape)

        for di, z in enumerate(depths_arr):
            shape_fn = 0.5 * (1 - np.tanh((z - thermocline_depth) / thermocline_width))
            profile = deep_temp + (sst[t] - deep_temp) * shape_fn
            noise = 0.15 * _smooth_random_field(rng, grid.shape)
            out[t, di] = profile + noise

    return out


