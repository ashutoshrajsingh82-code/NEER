"""
Synthetic demo ocean dataset generator for NEER — Phase 04.

Generates a deterministic, entirely SYNTHETIC ocean dataset over the
project's target domain (5N-30N, 45E-105E, 0.25 deg — configs/base.yaml)
and depth levels (0..1000 m, 15 levels — configs/base.yaml), for use as a
lightweight stand-in while no real satellite/ARGO data pipeline exists.

Variables generated (all on the shared NEER grid from src/data/grid.py):
    sst            (time, lat, lon)         Sea Surface Temperature   [degC]
    sss            (time, lat, lon)         Sea Surface Salinity      [psu]
    sla            (time, lat, lon)         Sea Level Anomaly         [m]
    u_current      (time, lat, lon)         Zonal surface current     [m/s]
    v_current      (time, lat, lon)         Meridional surface current[m/s]
    u_wind         (time, lat, lon)         Zonal wind                [m/s]
    v_wind         (time, lat, lon)         Meridional wind           [m/s]
    subsurface_temp(time, depth, lat, lon)  Subsurface temperature    [degC]
    land_mask      (lat, lon)               True = ocean, False = land

The fields are built from simple, deterministic, physically-*motivated*
components (climatological gradients, an idealised monsoon seasonal
cycle, mesoscale-eddy-like Gaussian anomalies, an approximate geostrophic
relation between SLA and currents, a tanh thermocline profile) plus
seeded random noise and gaps. They are designed to *look* like plausible
ocean fields for demoing pipelines/UI end-to-end — they are NOT measured,
reanalyzed, or physically simulated data of any kind.

===========================================================================
IMPORTANT — DATA PROVENANCE
===========================================================================
This dataset is 100% synthetic. It is generated from closed-form formulas
and a seeded pseudo-random number generator (seed=42 by default, from
configs/base.yaml -> demo.seed). It must NEVER be described, labeled, or
used as if it were real satellite, ARGO float, reanalysis, or any other
kind of observational or scientifically validated data. Every output file
carries `"data_mode": "DEMO_SYNTHETIC"` plus an explicit disclaimer in its
metadata for exactly this reason. Do not strip that metadata downstream.
===========================================================================

Usage
-----
    python scripts/create_demo_data.py
    python scripts/create_demo_data.py --n-time 12 --seed 42 --overwrite
"""

