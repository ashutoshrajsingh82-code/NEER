def _cloud_like_gap_mask(
    rng: np.random.Generator, shape: Tuple[int, int], missing_fraction: float
) -> np.ndarray:
    """Boolean mask, True where data is MISSING, in spatially-correlated
    'cloud swath'-like patches rather than independent per-pixel dropout.
    """
    field = _smooth_random_field(rng, shape, smoothing=15)
    # Threshold chosen (numerically, per-call) so the missing fraction is
    # approximately `missing_fraction` of the field.
    threshold = np.quantile(field, 1.0 - missing_fraction)
    return field >= threshold


def apply_missing_values(
    data: Dict[str, np.ndarray],
    ocean_mask: np.ndarray,
    rng: np.random.Generator,
    surface_missing_frac: float = 0.12,
    subsurface_missing_frac: float = 0.55,
) -> None:
    """Mask land everywhere (NaN) and punch realistic-looking gaps into the
    ocean points too: light cloud-like gaps for gridded surface fields,
    heavier gaps for subsurface temperature (ARGO float coverage is far
    sparser than satellite swath coverage). Modifies `data` in place.
    """
    land_mask = ~ocean_mask
    surface_vars = ("sst", "sss", "sla", "u_current", "v_current", "u_wind", "v_wind")

    for name in surface_vars:
        arr = data[name]
        for t in range(arr.shape[0]):
            gaps = _cloud_like_gap_mask(rng, arr.shape[1:], surface_missing_frac)
            arr[t][land_mask | gaps] = np.nan

    subsurface = data["subsurface_temp"]
    for t in range(subsurface.shape[0]):
        for di in range(subsurface.shape[1]):
            gaps = _cloud_like_gap_mask(rng, subsurface.shape[2:], subsurface_missing_frac)
            subsurface[t, di][land_mask | gaps] = np.nan


