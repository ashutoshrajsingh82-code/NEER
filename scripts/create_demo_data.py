def build_land_ocean_mask(lat_grid: np.ndarray, lon_grid: np.ndarray) -> np.ndarray:
    """Build a deliberately SIMPLIFIED/SCHEMATIC ocean mask for the domain.

    This is a hand-built geometric approximation of the broad Arabian
    Sea / Bay of Bengal / Indian-peninsula coastline layout used only to
    give the synthetic dataset a plausible land/ocean pattern to mask
    against. It is NOT a real coastline product and must not be treated
    as one.

    Returns
    -------
    np.ndarray of bool, shape (n_lat, n_lon): True = ocean, False = land.
    """
    lat = lat_grid
    lon = lon_grid
    land = np.zeros(lat.shape, dtype=bool)

    # Above ~25.5N the domain is dominated by the Iranian/Pakistani/Tibetan
    # landmass, with only a narrow Gulf-of-Oman-like taper of ocean left.
    high_lat_land = lat > 25.5
    oman_taper = (lat > 24.0) & (lat <= 26.5) & (lon >= 56.0) & (lon <= 68.0)
    land |= high_lat_land & ~oman_taper

    # Arabian Peninsula (Yemen/Oman/Saudi coast): a wedge along the western
    # edge of the domain, tapering as latitude decreases.
    arabia = (lat > 12.0) & (lon <= (58.0 - 0.35 * (lat - 12.0)))
    land |= arabia

    # Horn of Africa (Somalia coast): a wedge in the low-lon, low-lat corner.
    horn_of_africa = (lat <= 12.0) & (lon <= (46.5 + 0.35 * lat))
    land |= horn_of_africa

    # Indian peninsula: a wedge narrowing to a point near Cape Comorin
    # (~8N, 77E) and widening northward into the subcontinent, splitting
    # the Arabian Sea (west) from the Bay of Bengal (east).
    in_peninsula_lat = (lat >= 8.0) & (lat <= 25.5)
    lat_c = np.clip(lat, 8.0, 24.0)
    west_bound = 77.0 - (77.0 - 68.0) * (lat_c - 8.0) / (24.0 - 8.0)
    lat_e = np.clip(lat, 8.0, 22.0)
    east_bound = np.where(
        lat <= 22.0,
        78.0 + (91.0 - 78.0) * (lat_e - 8.0) / (22.0 - 8.0),
        91.0 + (lat - 22.0) * 1.5,  # Bengal/Bangladesh coast bulging east
    )
    peninsula = in_peninsula_lat & (lon >= west_bound) & (lon <= east_bound)
    land |= peninsula

    # Sri Lanka: a small island south of the peninsula tip.
    sri_lanka = ((lat - 7.5) ** 2 / 1.3**2 + (lon - 80.7) ** 2 / 1.0**2) <= 1.0
    land |= sri_lanka

    # Andaman & Nicobar chain: a broken line of small islands.
    andaman_strip = (lat >= 6.0) & (lat <= 14.0) & (np.abs(lon - 93.0) < 0.35)
    andaman_islands = andaman_strip & (np.sin(lat * 3.2) > -0.2)
    land |= andaman_islands

    # A couple of tiny Lakshadweep/Maldives-like dots for texture.
    for dot_lat, dot_lon in ((10.5, 72.7), (6.0, 73.1)):
        land |= ((lat - dot_lat) ** 2 + (lon - dot_lon) ** 2) <= 0.03**2

    return ~land  # ocean mask


